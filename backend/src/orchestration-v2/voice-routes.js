// ======================================================
// orchestration-v2/voice-routes — voice reference of a hero (VOICE_REFERENCES.md,
// VBOOK_FORMAT_V4 §5.2, HERO_CARD.md §6)
// ======================================================
// VBook 4 step 4: the routes of the reference-voices task moved from
// /voices/... to the hero (one hero = one resource). Prefix
// /api/v1/book/:bookId/heroes/:heroId/voice:
//
//   GET    /candidates            → {candidates:[{name, file, sha256, ref_text, source, model, seed,
//                                     verification, duration_ms, pinned, status, …}], pending, …}
//   POST   /candidates/design     {count?, client_action:{action_id}}  — explicit command
//   POST   /candidates/upload     multipart: file (wav|mp3|ogg|flac), ref_text?, client_action (JSON)
//                                  — explicit command
//   DELETE /candidates/:name      delete a candidate (not the pinned one)
//   GET    /file/:name            the candidate's audio (player)
//   POST   /reference             {name, locked: true, ref_text?}  pin (select + lock)
//   DELETE /reference             unpin (the candidate file stays)
//
// `name` is the candidate's file name inside build_<book>/voices/<hero>/ —
// "<candidate id>.wav", nothing else. The old /voices/references, /voices/:id/...
// routes are gone.
//
// Generation happens ONLY on an explicit command (COMMAND_ONLY_GENERATION):
// both POSTs that create GPU work require client_action.action_id. Books on the
// legacy orchestration get 409 book_not_v2 for the commands and for pinning;
// reading, listening, deleting a candidate and unpinning work for any book.
//
// Writes of the hero go through the hero store of the editor model (the
// runtime's character store: read → change → validate → atomic write) — never
// through a rewrite of the whole book. Pinning stores sha256 of the timbre the
// reference was made from (source_timbre_sha256, owner's decision 18.11); the
// API then reports voice.reference_outdated. Nothing is regenerated by itself.
//
// Access: the /api/v1/book/:bookId guard of backend.cjs (requireBookAccess) and
// the heroId / name param guards run before these handlers.

'use strict';

const fs = require('fs');
const voicePort = require('@animastor/vbook-runtime/voice');
const { isCanonicalHeroId, findHero } = require('@animastor/vbook-runtime/heroes.cjs');
const { VoiceReferenceError, phraseForVoice, MIN_DURATION_SEC, MAX_DURATION_SEC } = require('../audio/voice-references');
const { singleUpload } = require('../middleware/input-guard');

const UUID_RE = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;
const NAME_RE = /^([A-Za-z0-9_-]{1,128})\.wav$/;
const MAX_UPLOAD_BYTES = 20 * 1024 * 1024;
const UPLOAD_MIME_BY_EXT = Object.freeze({ wav: 'audio/wav', mp3: 'audio/mpeg', ogg: 'audio/ogg', flac: 'audio/flac' });
const MAX_REF_TEXT = 2000;

// errors of the hero store (runtime character store) → HTTP
const STORE_STATUS = Object.freeze({ hero_file_broken: 409, invalid_character: 400, path_is_link: 409, invalid_hero_id: 400, voice_not_found: 404, bad_reference: 409 });

function sendError(res, err, ctx) {
    const status = Number(err && err.status) || STORE_STATUS[err && err.code] || 500;
    if (status >= 500) console.error(`[VOICE-REF] ${ctx}: ${err && err.message}`);
    const details = err && err.details && typeof err.details === 'object' ? err.details : {};
    const code = (err && err.code) || 'internal';
    // The hero API shape ({error: <code>, message}); `code` is kept for the
    // clients of the reference-voices task.
    return res.status(status).json({ ...details, error: code, code, message: (err && err.message) || 'error' });
}

function actionIdOf(clientAction) {
    let ca = clientAction;
    if (typeof ca === 'string') {
        try { ca = JSON.parse(ca); } catch (_) { ca = null; }
    }
    return ca && typeof ca === 'object' && typeof ca.action_id === 'string' && ca.action_id ? ca.action_id.slice(0, 200) : null;
}

function mountVoiceRoutes(app, { host, editorModel, bookRepo, getPool, log = console.log }) {
    const refs = () => host.voiceRefs();
    const prefix = '/api/v1/book/:bookId/heroes/:heroId/voice';

    function userIdOf(req) {
        const u = req.user && (req.user.user_id || req.user.id);
        if (u && UUID_RE.test(String(u))) return String(u);
        const g = req.guest && req.guest.guestId;
        return g && UUID_RE.test(String(g)) ? String(g) : null;
    }

    async function requireV2(bookId) {
        if (!host.isEnabled()) throw new VoiceReferenceError('orch_v2_disabled', 503, host.disabledReason() || 'orchestration v2 is disabled');
        if (!(await host.isV2Book(bookId))) throw new VoiceReferenceError('book_not_v2', 409, 'voice references need orchestration v2 (books.orchestration = v2)');
    }

    /** The book and the hero of the request; the hero must exist and have a voice block. */
    function loadHero(req, { needVoice = true } = {}) {
        const { bookId, heroId } = req.params;
        if (!isCanonicalHeroId(heroId)) throw new VoiceReferenceError('invalid_hero_id', 400, `invalid hero id ${JSON.stringify(heroId)}`);
        const b = editorModel.read(bookId);
        if (!b) throw new VoiceReferenceError('book_not_found', 404, `book ${bookId} not found`);
        const hero = findHero(b, heroId);
        if (!hero) throw new VoiceReferenceError('hero_not_found', 404, `hero ${heroId} not found`);
        if (needVoice && !voicePort.getCharacterVoice(b, heroId)) {
            throw new VoiceReferenceError('voice_not_found', 404, `hero ${heroId} has no voice block`);
        }
        return { bookId, heroId, book: b, hero };
    }

    function candidateIdOf(name) {
        const m = typeof name === 'string' ? NAME_RE.exec(name) : null;
        if (!m) throw new VoiceReferenceError('invalid_name', 400, 'name: the candidate file name "<id>.wav"');
        return m[1];
    }

    async function commandOwner(req, bookId) {
        const workspaceId = await bookRepo.getWorkspaceId(bookId);
        if (!workspaceId) throw new VoiceReferenceError('book_without_workspace', 409, 'book has no workspace');
        let userId = userIdOf(req);
        if (!userId) {
            const ws = await require('../storage/postgres/repositories/workspace-repo').findById(workspaceId).catch(() => null);
            userId = ws && ws.owner_user_id ? ws.owner_user_id : null;
        }
        if (!userId) throw new VoiceReferenceError('unauthorized', 401, 'no user for the command');
        return { workspaceId, userId };
    }

    /** pending candidates whose job ended without a result → failed (visible in the UI) */
    async function reconcilePending(loadedBook, bookId, heroId, candidates) {
        const pending = candidates.filter((c) => c.status === 'pending').map((c) => c.candidate_id);
        if (!pending.length || typeof getPool !== 'function') return candidates;
        const rows = (await getPool().query(
            `SELECT DISTINCT ON (unit_key) unit_key, status, error FROM gen_jobs
             WHERE book_id = $1 AND kind = 'voice_reference' AND scene_id = $2 AND unit_key = ANY($3::text[])
             ORDER BY unit_key, created_at DESC`, [bookId, heroId, pending])).rows;
        let changed = false;
        for (const r of rows) {
            if (r.status === 'failed' || r.status === 'cancelled') {
                refs().markCandidateFailed(refs().buildIdOf(loadedBook), heroId, r.unit_key, r.error || r.status);
                changed = true;
            }
        }
        return changed ? refs().listCandidates(loadedBook, heroId) : candidates;
    }

    /** Candidate metadata → the API item of HERO_CARD §6. */
    function candidateItem(c, pinnedId) {
        const item = {
            name: `${c.candidate_id}.wav`,
            candidate_id: c.candidate_id,
            status: c.status,
            source: c.source || null,
            file: c.file || null,
            sha256: c.sha256 || null,
            ref_text: typeof c.ref_text === 'string' ? c.ref_text : null,
            ref_text_source: c.ref_text_source || null,
            model: c.model || null,
            seed: Number.isSafeInteger(c.seed) ? c.seed : null,
            verification: c.verification || null,
            verification_problems: Array.isArray(c.verification_problems) ? c.verification_problems : [],
            duration_ms: typeof c.duration_sec === 'number' ? Math.round(c.duration_sec * 1000) : null,
            created_at: c.created_at || null,
            pinned: !!pinnedId && c.candidate_id === pinnedId,
        };
        if (c.error) item.error = c.error;
        return item;
    }

    // ── list (reads only) ───────────────────────────────────────────────
    app.get(`${prefix}/candidates`, async (req, res) => {
        try {
            const { bookId, heroId, book } = loadHero(req);
            const v = voicePort.getCharacterVoice(book, heroId);
            const st = refs().referenceStatus(book, heroId);
            const raw = await reconcilePending(book, bookId, heroId, refs().listCandidates(book, heroId));
            const pinnedId = v.reference ? v.reference.candidate_id || null : null;
            let phrase = null;
            try { const p = phraseForVoice(book, heroId); phrase = { id: p.id, version: p.version, style: p.style, text: p.text, language: p.language }; } catch (_) { /* language unsupported */ }
            const candidates = raw.map((c) => candidateItem(c, pinnedId));
            return res.json({
                book_id: bookId, hero_id: heroId,
                candidates,
                pending: candidates.some((c) => c.status === 'pending'),
                reference_status: st.status,
                reference_outdated: voicePort.isReferenceOutdated(v),
                design_description: voicePort.voiceDesignDescription(v),
                phrase,
                duration_bounds_sec: [MIN_DURATION_SEC, MAX_DURATION_SEC],
            });
        } catch (err) { return sendError(res, err, 'list'); }
    });

    // ── create candidates (explicit command) ────────────────────────────
    app.post(`${prefix}/candidates/design`, async (req, res) => {
        try {
            const body = req.body || {};
            const actionId = actionIdOf(body.client_action);
            if (!actionId) return sendError(res, new VoiceReferenceError('no_user_action', 400, 'voice candidates are created only by an explicit user action (client_action.action_id)'), 'design');
            const { bookId, heroId, book } = loadHero(req);
            await requireV2(bookId);
            if (refs().referenceStatus(book, heroId).status === 'ok') {
                throw new VoiceReferenceError('reference_locked', 409, 'a pinned reference is present (unpin it first)', { character_ids: [heroId] });
            }
            const owner = await commandOwner(req, bookId);
            const r = await host.orch().createCommand({
                ...owner, bookId, kind: 'voice_reference', layers: ['audio'], clientActionId: actionId,
                scope: { level: 'book', voice: { mode: 'design', character_ids: [heroId], count: body.count } },
            });
            log(`[VOICE-REF] ${bookId}/${heroId}: candidates command ${r.command_id} ${r.existing ? '(repeated click)' : 'created'} summary=${JSON.stringify(r.summary)}`);
            return res.json({ book_id: bookId, hero_id: heroId, command_id: r.command_id, existing: r.existing, summary: r.summary });
        } catch (err) { return sendError(res, err, 'design'); }
    });

    // ── upload own sample (explicit command) ────────────────────────────
    app.post(`${prefix}/candidates/upload`, singleUpload('file', { fileSize: MAX_UPLOAD_BYTES }), async (req, res) => {
        try {
            const body = req.body || {};
            const actionId = actionIdOf(body.client_action) || (typeof req.query.action_id === 'string' && req.query.action_id ? req.query.action_id.slice(0, 200) : null);
            if (!actionId) return sendError(res, new VoiceReferenceError('no_user_action', 400, 'an upload is accepted only from an explicit user action (client_action.action_id)'), 'upload');
            if (!req.file || !Buffer.isBuffer(req.file.buffer)) throw new VoiceReferenceError('bad_request', 400, 'multipart field "file" is required');
            const refText = typeof body.ref_text === 'string' ? body.ref_text.trim() : '';
            if (refText.length > MAX_REF_TEXT) throw new VoiceReferenceError('bad_request', 400, `ref_text: at most ${MAX_REF_TEXT} characters`);
            const { bookId, heroId, book } = loadHero(req);
            await requireV2(bookId);
            if (refs().referenceStatus(book, heroId).status === 'ok') {
                throw new VoiceReferenceError('reference_locked', 409, 'a pinned reference is present (unpin it first)', { character_ids: [heroId] });
            }
            // the media type of the part, else the extension of its name
            const ext = String(req.file.originalname || '').toLowerCase().match(/\.(wav|mp3|ogg|flac)$/);
            const mime = req.file.mimetype && req.file.mimetype !== 'application/octet-stream'
                ? req.file.mimetype : (ext ? UPLOAD_MIME_BY_EXT[ext[1]] : '');
            const scopeVoice = refs().storeUpload(book, heroId, req.file.buffer, mime);
            if (refText) scopeVoice.ref_text = refText;
            const owner = await commandOwner(req, bookId);
            const r = await host.orch().createCommand({
                ...owner, bookId, kind: 'voice_reference', layers: ['audio'], clientActionId: actionId,
                scope: { level: 'book', voice: scopeVoice },
            });
            log(`[VOICE-REF] ${bookId}/${heroId}: upload ${scopeVoice.candidate_id} (${scopeVoice.upload.bytes} B) → command ${r.command_id}`);
            return res.json({ book_id: bookId, hero_id: heroId, command_id: r.command_id, name: `${scopeVoice.candidate_id}.wav`, candidate_id: scopeVoice.candidate_id, summary: r.summary });
        } catch (err) { return sendError(res, err, 'upload'); }
    });

    // ── listen ──────────────────────────────────────────────────────────
    app.get(`${prefix}/file/:name`, (req, res) => {
        try {
            const candId = candidateIdOf(req.params.name);
            const { heroId, book } = loadHero(req, { needVoice: false });
            const p = refs().paths.candidateWav(refs().buildIdOf(book), heroId, candId);
            let st = null;
            try { st = fs.lstatSync(p); } catch (_) { st = null; }
            if (!st || !st.isFile()) return sendError(res, new VoiceReferenceError('not_found', 404, 'audio not found'), 'audio');
            res.setHeader('Content-Type', 'audio/wav');
            res.setHeader('Content-Length', String(st.size));
            res.setHeader('Cache-Control', 'no-store');
            return fs.createReadStream(p).pipe(res);
        } catch (err) { return sendError(res, err, 'audio'); }
    });

    // ── delete candidate ────────────────────────────────────────────────
    app.delete(`${prefix}/candidates/:name`, (req, res) => {
        try {
            const candId = candidateIdOf(req.params.name);
            const { bookId, heroId, book } = loadHero(req, { needVoice: false });
            refs().deleteCandidate(book, heroId, candId);
            log(`[VOICE-REF] ${bookId}/${heroId}: candidate ${candId} deleted`);
            return res.json({ deleted: true, book_id: bookId, hero_id: heroId, name: req.params.name });
        } catch (err) { return sendError(res, err, 'delete'); }
    });

    // ── pin (select + lock) ─────────────────────────────────────────────
    app.post(`${prefix}/reference`, async (req, res) => {
        try {
            const body = req.body || {};
            if (body.locked !== undefined && body.locked !== true) {
                throw new VoiceReferenceError('locked_required', 400, 'a reference is pinned with locked: true (unpin is DELETE)');
            }
            const candId = candidateIdOf(body.name);
            if (body.ref_text !== undefined && body.ref_text !== null && typeof body.ref_text !== 'string') {
                throw new VoiceReferenceError('bad_request', 400, 'ref_text must be a string');
            }
            const { bookId, heroId, book } = loadHero(req);
            await requireV2(bookId);
            let reference = null;
            // point write of this hero: the candidate is checked against the
            // file on disk inside the same synchronous step as the write
            const written = editorModel.heroes(bookId).update(heroId, (hero) => {
                const one = { manifest: book.manifest, book: book.book, heroes: [hero] };
                refs().selectCandidate(one, heroId, candId, { refText: body.ref_text });
                // only a designed reference comes from the timbre text, so only
                // it remembers the timbre (owner's decision 18.11, step 5)
                if (hero.voice.reference.source === 'designed') {
                    hero.voice.reference.source_timbre_sha256 = voicePort.timbreSha256(hero.voice.timbre);
                } else {
                    delete hero.voice.reference.source_timbre_sha256;
                }
                reference = hero.voice.reference;
                return hero;
            });
            if (!written) throw new VoiceReferenceError('hero_not_found', 404, `hero ${heroId} not found`);
            log(`[VOICE-REF] ${bookId}/${heroId}: pinned ${candId} sha=${reference.sha256.slice(0, 12)} source=${reference.source}`);
            return res.json({ saved: true, book_id: bookId, hero_id: heroId, reference });
        } catch (err) { return sendError(res, err, 'pin'); }
    });

    // ── unpin (the candidate file stays) ────────────────────────────────
    app.delete(`${prefix}/reference`, (req, res) => {
        try {
            const { bookId, heroId } = loadHero(req);
            editorModel.heroes(bookId).update(heroId, (hero) => {
                if (hero.voice && typeof hero.voice === 'object') delete hero.voice.reference;
                return hero;
            });
            log(`[VOICE-REF] ${bookId}/${heroId}: reference unpinned`);
            return res.json({ saved: true, book_id: bookId, hero_id: heroId, reference: null });
        } catch (err) { return sendError(res, err, 'unpin'); }
    });
}

module.exports = { mountVoiceRoutes, NAME_RE };
